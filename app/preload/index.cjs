    zoom: (tab, action) => ipcRenderer.invoke("atlas:browser-zoom", tab, action),
    devices: () => ipcRenderer.invoke("atlas:browser-devices"),
    device: (tab, device) => ipcRenderer.invoke("atlas:browser-device", tab, device),
    screenshotData: (tab) => ipcRenderer.invoke("atlas:browser-screenshot-data", tab),
    screenshotSave: (tab) => ipcRenderer.invoke("atlas:browser-screenshot-save", tab),
    navHistory: (tab) => ipcRenderer.invoke("atlas:browser-nav-history", tab),
    goTo: (tab, index) => ipcRenderer.invoke("atlas:browser-goto", tab, index),
    selection: (tab) => ipcRenderer.invoke("atlas:browser-selection", tab),
    clear: (options) => ipcRenderer.invoke("atlas:browser-clear", options),
    onFind: (cb) => listen("atlas:browser-found", cb),
    onFindOpen: (cb) => listen("atlas:browser-find-open", cb),
    expect: (tab) => ipcRenderer.invoke("atlas:browser-expect", tab),
