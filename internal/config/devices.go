package config

// ToolDevices configures device automation: isolated desktops (Windows
// Sandbox), Android devices over adb, paired remote computers (nodes),
// screen marks and the live app loop. Off by default: these tools reach
// beyond the workspace, so turning them on is an explicit opt-in. The phone
// gateway is separate and only starts from /mobile.
type ToolDevices struct {
	Enabled *bool  `json:"enabled,omitempty" jsonschema:"description=Turn on the device tools (isolated_desktop, android, remote_node, screen_mark, app_loop). Their schemas still load on demand through tool_search.,default=false"`
	ADBPath string `json:"adb_path,omitempty" jsonschema:"description=Path to adb from Android SDK Platform-Tools. Default: ANDROID_SDK_ROOT or ANDROID_HOME platform-tools, then PATH.,example=C:/Android/Sdk/platform-tools/adb.exe"`
	// MobileListen is the phone gateway address. Loopback unless MobileLAN.
	MobileListen string `json:"mobile_listen,omitempty" jsonschema:"description=Phone gateway listen address. Defaults to 127.0.0.1:7777; non-loopback addresses also need mobile_lan.,example=0.0.0.0:7777"`
	MobileLAN    bool   `json:"mobile_lan,omitempty" jsonschema:"description=Allow the phone gateway on the local network (HTTPS with a self-signed certificate). Never exposed to the internet by Atlas.,default=false"`
	// MobileHosts are exact extra hostnames for the phone gateway, such as a
	// Tailscale MagicDNS name. They are added to the certificate and the
	// allowed Host list; wildcards are rejected.
	MobileHosts []string `json:"mobile_hosts,omitempty" jsonschema:"description=Exact extra hostnames the phone may use to reach the gateway (for example a Tailscale MagicDNS name). Needs mobile_lan. Wildcards, ports and IP addresses are rejected.,example=home-pc.tail1234.ts.net"`
	// MobileTLSCert and MobileTLSKey optionally use an existing certificate
	// the phone trusts, instead of the generated self-signed identity.
	MobileTLSCert string `json:"mobile_tls_cert,omitempty" jsonschema:"description=Optional absolute path to a PEM TLS certificate chain trusted by the phone (for example tailscale cert output). Requires mobile_tls_key. Only configured or local interface hosts covered by this certificate are advertised."`
	MobileTLSKey  string `json:"mobile_tls_key,omitempty" jsonschema:"description=Optional absolute path to the corresponding PEM private key. Keep this outside the workspace. Requires mobile_tls_cert; invalid or expired certificates fail startup instead of falling back."`
	// Relay mode needs no phone app, LAN binding or inbound home firewall rule.
	MobileRelayURL       string `json:"mobile_relay_url,omitempty" jsonschema:"description=Optional dedicated HTTPS origin of your own Atlas mobile-relay server. Atlas connects outbound; Safari reaches this origin from anywhere. Requires mobile_relay_token_file. The relay is trusted with phone traffic and must be yours."`
	MobileRelayTokenFile string `json:"mobile_relay_token_file,omitempty" jsonschema:"description=Absolute path to the private connector key shared with your own mobile-relay server. Generate with mobile-relay keygen and keep outside the workspace. Never put this key in a URL or phone browser."`
	// RemoteProfiles are servers managed from /rc. They hold references to
	// secrets, never the secrets themselves.
	RemoteProfiles []RemoteProfile `json:"remote_profiles,omitempty" jsonschema:"description=Relay servers managed from /rc. Passwords and key passphrases are stored sealed outside this file; only references are kept here."`
	// RemoteActive names the profile /rc uses.
	RemoteActive string `json:"remote_active,omitempty" jsonschema:"description=ID of the active remote_profiles entry used by /rc."`
}

// RemoteProfile is one relay server managed from /rc. The SSH target and the
// HTTPS address phones open are separate: they may be different names.
type RemoteProfile struct {
	ID   string `json:"id" jsonschema:"description=Stable profile identifier generated by /rc."`
	Name string `json:"name" jsonschema:"description=Display name of the profile."`
	// SSHHost is an IPv4 or IPv6 address or a hostname, without a port.
	SSHHost string `json:"ssh_host" jsonschema:"description=Server IP address or SSH hostname without a port.,example=203.0.113.10"`
	SSHPort int    `json:"ssh_port,omitempty" jsonschema:"description=SSH port.,default=22,minimum=1,maximum=65535"`
	SSHUser string `json:"ssh_user" jsonschema:"description=SSH user name. Needs root or passwordless sudo on the server.,example=ubuntu"`
	// SSHAuth is key, agent or password.
	SSHAuth string `json:"ssh_auth" jsonschema:"description=SSH authentication method.,enum=key,enum=agent,enum=password"`
	// SSHKeyFile references a private key file; its content is never copied.
	SSHKeyFile string `json:"ssh_key_file,omitempty" jsonschema:"description=Absolute path to the SSH private key when ssh_auth is key. The key itself is never copied into Atlas configuration."`
	// SecretRef names a sealed password or key passphrase stored by /rc.
	SecretRef string `json:"secret_ref,omitempty" jsonschema:"description=Reference to a password or key passphrase sealed by /rc with operating-system protection. Not a secret by itself."`
	// PublicHost is the dedicated HTTPS hostname phones open.
	PublicHost string `json:"public_host" jsonschema:"description=Dedicated hostname phones open over HTTPS. Its DNS A/AAAA records must point to the server.,example=atlas.example.com"`
	// ACMEEmail is an optional certificate contact address.
	ACMEEmail string `json:"acme_email,omitempty" jsonschema:"description=Optional e-mail address given to the certificate authority for expiry notices."`
	// ConnectTimeout bounds the SSH connection, in seconds.
	ConnectTimeout int `json:"connect_timeout_seconds,omitempty" jsonschema:"description=SSH connection timeout in seconds.,default=15,minimum=3,maximum=120"`
	// IgnoreUserKnownHosts stops /rc from reading ~/.ssh/known_hosts. /rc
	// never writes that file either way.
	IgnoreUserKnownHosts bool `json:"ignore_user_known_hosts,omitempty" jsonschema:"description=Do not read ~/.ssh/known_hosts; only host keys accepted in /rc are trusted. /rc never writes ~/.ssh/known_hosts.,default=false"`
}

// Port returns the SSH port, defaulting to 22.
func (p RemoteProfile) Port() int {
	if p.SSHPort == 0 {
		return 22
	}
	return p.SSHPort
}

// Timeout returns the SSH connection timeout in seconds, defaulting to 15.
func (p RemoteProfile) Timeout() int {
	if p.ConnectTimeout == 0 {
		return 15
	}
	return p.ConnectTimeout
}

// IsEnabled reports whether the device tools should be registered.
func (t ToolDevices) IsEnabled() bool { return ptrValOr(t.Enabled, false) }
